#!/usr/bin/env python3
"""Verify the clock used by Taiwan market schedules and repair bounded WSL drift.

``timedatectl`` reports whether a synchronization service is enabled, not
whether chronyd currently has a usable source.  On WSL the Windows host is the
clock authority, so compare both clocks directly.  On native Linux require a
selected chrony source.  Every run writes an atomic receipt; a large offset is
never stepped automatically.
"""

from __future__ import annotations

import argparse
import ctypes
from datetime import datetime
import fcntl
import json
import math
import os
from pathlib import Path
import select
import shutil
import subprocess
import sys
import time
from typing import Any, Callable
import uuid
from zoneinfo import ZoneInfo


REPO_ROOT = Path(__file__).resolve().parents[1]
TAIPEI = ZoneInfo("Asia/Taipei")
WSL_RATE_GUARD_CONTRACT = "wsl_kernel_rate_stability_guard_v1"
WSL_RATE_REQUIRED_GOOD_SAMPLES = 5
WSL_RATE_MAX_ESTIMATED_DEVIATION_PPM = 500.0
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--receipt",
        type=Path,
        default=Path("artifacts/operations/time_sync/latest.json"),
    )
    parser.add_argument("--repair", action="store_true")
    parser.add_argument("--max-offset-ms", type=float, default=500.0)
    parser.add_argument("--max-repair-offset-seconds", type=float, default=300.0)
    parser.add_argument("--samples", type=int, default=3)
    return parser.parse_args()


def _repo_path(path: Path) -> Path:
    return path if path.is_absolute() else REPO_ROOT / path


def _atomic_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + f".tmp.{uuid.uuid4().hex}")
    try:
        with temporary.open("w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def _prune_managed_runs(
    directory: Path, *, max_files: int = 2048, max_age_days: int = 365
) -> None:
    """Bound only receipts generated by this checker."""

    try:
        rows = sorted(
            (path for path in directory.glob("*.json") if path.is_file()),
            key=lambda path: path.stat().st_mtime,
            reverse=True,
        )
    except OSError:
        return
    cutoff = time.time() - max_age_days * 86400
    for index, path in enumerate(rows):
        try:
            if index >= max_files or path.stat().st_mtime < cutoff:
                path.unlink(missing_ok=True)
        except OSError:
            continue


def _is_wsl() -> bool:
    try:
        release = Path("/proc/sys/kernel/osrelease").read_text(encoding="utf-8")
    except OSError:
        return False
    return "microsoft" in release.casefold()


def _powershell_path() -> str | None:
    discovered = shutil.which("powershell.exe")
    if discovered:
        return discovered
    candidate = Path(
        "/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe"
    )
    return str(candidate) if candidate.is_file() else None


def _interop_signature(path: str | Path) -> tuple | None:
    # Reuse the native I/O owner's socket, owner, and /init identity checks.
    from stockagent.data_sync.windows_cold_io import _interop_socket

    return _interop_socket(path)


def _windows_interop_candidates() -> list[tuple]:
    """Find bounded, structurally trusted bridges, including systemd's case."""

    from stockagent.data_sync.windows_cold_io import _INTEROP_DIRECTORY

    preferred = os.environ.get("WSL_INTEROP")
    paths = ([Path(preferred)] if preferred else []) + [
        _INTEROP_DIRECTORY / "1_interop",
        *sorted(_INTEROP_DIRECTORY.glob("*_interop"), reverse=True),
    ]
    candidates: list[tuple] = []
    seen: set[tuple] = set()
    for path in paths:
        signature = _interop_signature(path)
        if signature is None or signature in seen:
            continue
        seen.add(signature)
        candidates.append(signature)
        if len(candidates) == 4:
            break
    return candidates


class _WindowsClockHandshakeError(RuntimeError):
    """A candidate bridge could not start the host clock sampler."""


def _sample_windows_host_offset(
    *,
    samples: int,
) -> dict[str, Any]:
    executable = _powershell_path()
    if not executable:
        raise RuntimeError("powershell.exe is unavailable")
    # Start PowerShell once, then sample a request/response over its pipes.
    # Measuring process startup in every round trip biases the midpoint by
    # hundreds of milliseconds because the timestamp is taken near the end.
    command = (
        "[Console]::Out.WriteLine('READY'); [Console]::Out.Flush(); "
        "while ($null -ne ($l = [Console]::In.ReadLine())) { "
        "if ($l -ne 'S') { break }; "
        "[Console]::Out.WriteLine([DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()); "
        "[Console]::Out.Flush() }"
    )
    candidates = _windows_interop_candidates()
    if not candidates:
        raise RuntimeError("no trusted local WSL interop bridge for Windows host clock")
    # The guardian has a 20 s deadline, including chrony and receipt I/O.
    # A broken bridge must not stall the next opening readiness check.
    deadline = time.monotonic() + 12.0
    handshake_errors: list[str] = []
    for signature in candidates:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        try:
            return _sample_windows_clock_process(
                executable=executable,
                command=command,
                signature=signature,
                samples=samples,
                deadline=deadline,
            )
        except _WindowsClockHandshakeError as exc:
            handshake_errors.append(str(exc))
    raise RuntimeError(
        "Windows host clock bridge handshake failed: "
        + "; ".join(handshake_errors or ["deadline exhausted"])
    )


def _sample_windows_clock_process(
    *, executable: str, command: str, signature: tuple, samples: int, deadline: float,
) -> dict[str, Any]:
    bridge = str(signature[0])
    if _interop_signature(bridge) != signature:
        raise _WindowsClockHandshakeError("WSL interop identity changed before startup")
    try:
        process = subprocess.Popen(
            [executable, "-NoProfile", "-NonInteractive", "-Command", command],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            bufsize=0, env={**os.environ, "WSL_INTEROP": bridge},
        )
    except OSError as exc:
        raise _WindowsClockHandshakeError(f"Windows host process start: {type(exc).__name__}") from exc
    rows: list[dict[str, float]] = []
    pending = b""

    def read_line(timeout: float) -> bytes:
        nonlocal pending
        read_deadline = min(deadline, time.monotonic() + timeout)
        while b"\n" not in pending:
            remaining = read_deadline - time.monotonic()
            if remaining <= 0 or not select.select([process.stdout], [], [], remaining)[0]:
                raise TimeoutError("Windows host clock response timed out")
            chunk = os.read(process.stdout.fileno(), 128)
            if not chunk:
                raise RuntimeError("Windows host clock process exited")
            pending += chunk
            if len(pending) > 1024:
                raise ValueError("Windows host clock response is too long")
        line, pending = pending.split(b"\n", 1)
        return line.strip()

    try:
        try:
            if read_line(6.0) != b"READY":
                raise RuntimeError("Windows host clock did not acknowledge startup")
            if _interop_signature(bridge) != signature:
                raise RuntimeError("WSL interop identity changed during startup")
        except (RuntimeError, TimeoutError, ValueError) as exc:
            raise _WindowsClockHandshakeError(str(exc)) from exc
        for _ in range(max(1, int(samples))):
            before = time.time()
            before_mono = time.monotonic()
            process.stdin.write(b"S\n")
            process.stdin.flush()
            response = read_line(5.0)
            after_mono = time.monotonic()
            after = time.time()
            elapsed = after_mono - before_mono
            if abs((after - before) - elapsed) > 0.010:
                raise RuntimeError("local clock changed during host clock sample")
            host_seconds = int(response) / 1000.0
            rows.append({
                "offset_seconds": host_seconds - ((before + after) / 2.0),
                "round_trip_seconds": elapsed,
                "sample_monotonic_seconds": (before_mono + after_mono) / 2.0,
                # Host milliseconds are truncated; include their quantization.
                "uncertainty_seconds": elapsed / 2.0 + 0.001,
            })
        if _interop_signature(bridge) != signature:
            raise RuntimeError("WSL interop identity changed during clock sampling")
    finally:
        process.terminate()
        try:
            process.wait(timeout=0.5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=0.5)
        if process.stdin is not None:
            process.stdin.close()
        if process.stdout is not None:
            process.stdout.close()
    best = min(rows, key=lambda row: row["round_trip_seconds"])
    return {
        "source": "wsl_windows_host_clock",
        "offset_seconds": best["offset_seconds"],
        "round_trip_seconds": best["round_trip_seconds"],
        "uncertainty_seconds": best["uncertainty_seconds"],
        "sampling_method": "persistent_request_response_v1",
        "sample_count": len(rows),
        "sample_monotonic_seconds": best["sample_monotonic_seconds"],
    }


class _Timeval(ctypes.Structure):
    _fields_ = [("sec", ctypes.c_long), ("usec", ctypes.c_long)]


class _Timex(ctypes.Structure):
    # glibc Linux 64-bit ABI. Unsupported architectures fail closed instead of
    # making a syscall with a guessed struct layout.
    _fields_ = [
        ("modes", ctypes.c_uint), ("offset", ctypes.c_long), ("freq", ctypes.c_long),
        ("maxerror", ctypes.c_long), ("esterror", ctypes.c_long), ("status", ctypes.c_int),
        ("constant", ctypes.c_long), ("precision", ctypes.c_long), ("tolerance", ctypes.c_long),
        ("time", _Timeval), ("tick", ctypes.c_long), ("ppsfreq", ctypes.c_long),
        ("jitter", ctypes.c_long), ("shift", ctypes.c_int), ("stabil", ctypes.c_long),
        ("jitcnt", ctypes.c_long), ("calcnt", ctypes.c_long), ("errcnt", ctypes.c_long),
        ("stbcnt", ctypes.c_long), ("tai", ctypes.c_int), ("reserved", ctypes.c_int * 11),
    ]


def _adjtimex(value: _Timex) -> None:
    if value.modes != 0:
        raise ValueError("kernel clock discipline observation is read-only")
    if (sys.platform != "linux" or ctypes.sizeof(ctypes.c_long) != 8
            or os.uname().machine not in {"x86_64", "aarch64"}):
        raise RuntimeError("unsupported Linux time-discipline ABI")
    libc = ctypes.CDLL(None, use_errno=True)
    libc.adjtimex.argtypes = [ctypes.POINTER(_Timex)]
    libc.adjtimex.restype = ctypes.c_int
    if libc.adjtimex(ctypes.byref(value)) < 0:
        error = ctypes.get_errno()
        raise OSError(error, os.strerror(error))


def _kernel_time_discipline() -> dict[str, Any]:
    """Observe the kernel's rate separately from its current time offset."""
    value = _Timex()
    _adjtimex(value)
    user_hz = int(os.sysconf("SC_CLK_TCK"))
    if user_hz <= 0 or 1_000_000 % user_hz:
        raise ValueError("cannot determine an exact nominal kernel tick")
    return {"tick_us": int(value.tick), "nominal_tick_us": 1_000_000 // user_hz,
            "frequency_ppm": float(value.freq) / 65536.0, "status": int(value.status)}


def _chrony_tracking(
    *,
    runner: Callable[..., subprocess.CompletedProcess[str]] = subprocess.run,
) -> dict[str, Any]:
    completed = runner(
        ["chronyc", "-c", "tracking"],
        check=True,
        capture_output=True,
        text=True,
        timeout=5,
    )
    fields = completed.stdout.strip().split(",")
    if len(fields) < 14:
        raise RuntimeError("chronyc tracking returned an incomplete row")
    return {
        "source": "chrony_selected_source",
        "reference_id": fields[0],
        "reference_name": fields[1],
        "stratum": int(fields[2]),
        "system_offset_seconds": float(fields[4]),
        "last_offset_seconds": float(fields[5]),
        "rms_offset_seconds": float(fields[6]),
        "root_delay_seconds": float(fields[10]),
        "root_dispersion_seconds": float(fields[11]),
        "leap_status": fields[13],
    }


def _attempt_chrony_repair() -> dict[str, Any]:
    attempts: list[dict[str, Any]] = []
    for command, timeout in (
        (["chronyc", "online"], 5),
        (["chronyc", "burst", "4/8"], 5),
        (["chronyc", "waitsync", "10", "0.5", "0", "1"], 15),
        (["chronyc", "makestep"], 5),
    ):
        completed = subprocess.run(
            command,
            check=False,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        attempts.append(
            {
                "command": command,
                "returncode": int(completed.returncode),
                "stdout": completed.stdout[-500:],
                "stderr": completed.stderr[-500:],
            }
        )
        if command[1] == "waitsync" and completed.returncode != 0:
            break
    return {"attempts": attempts}


def evaluate_time_sync(
    *,
    repair: bool,
    max_offset_ms: float,
    max_repair_offset_seconds: float,
    samples: int,
) -> dict[str, Any]:
    started = datetime.now(TAIPEI)
    failures: list[str] = []
    repaired = False
    authority: dict[str, Any] = {}
    chrony: dict[str, Any] = {}
    repair_evidence: dict[str, Any] = {}
    try:
        chrony = _chrony_tracking()
    except Exception as exc:
        chrony = {"error": f"{type(exc).__name__}: {exc}"}

    try:
        if _is_wsl():
            authority = _sample_windows_host_offset(samples=samples)
            offset_seconds = float(authority["offset_seconds"])
            uncertainty = float(authority.get(
                "uncertainty_seconds", float(authority["round_trip_seconds"]) / 2.0 + 0.001
            ))
            if not math.isfinite(offset_seconds) or not math.isfinite(uncertainty) or uncertainty < 0:
                raise ValueError("invalid WSL clock offset or uncertainty")
            discipline = _kernel_time_discipline()
            tick, nominal = int(discipline["tick_us"]), int(discipline["nominal_tick_us"])
            frequency_ppm = float(discipline["frequency_ppm"])
            if tick <= 0 or nominal <= 0 or not math.isfinite(frequency_ppm):
                raise ValueError("kernel tick or frequency is invalid")
            estimated_rate_ppm = (tick / nominal - 1.0) * 1_000_000.0 + frequency_ppm
            discipline["estimated_combined_rate_deviation_ppm"] = estimated_rate_ppm
            repair_evidence["kernel_time_discipline"] = discipline
            if abs(estimated_rate_ppm) > WSL_RATE_MAX_ESTIMATED_DEVIATION_PPM:
                # A separate NTP owner can change the shared WSL clock between
                # observations. Stepping it repeatedly or resetting its rate
                # would fight that owner and still give false readiness.
                failures.append("WSL kernel tick rate is abnormal and is not continuously synchronized")
            lower_bound = max(0.0, abs(offset_seconds) - uncertainty)
            upper_bound = abs(offset_seconds) + uncertainty
            if lower_bound * 1000.0 > float(max_offset_ms) and repair and not failures:
                if upper_bound > float(max_repair_offset_seconds):
                    failures.append(
                        "WSL host clock offset exceeds the bounded auto-repair limit"
                    )
                else:
                    time.clock_settime(time.CLOCK_REALTIME, time.time() + offset_seconds)
                    repaired = True
                    authority = _sample_windows_host_offset(samples=samples)
                    offset_seconds = float(authority["offset_seconds"])
                    uncertainty = float(authority.get(
                        "uncertainty_seconds", float(authority["round_trip_seconds"]) / 2.0 + 0.001
                    ))
                    if not math.isfinite(offset_seconds) or not math.isfinite(uncertainty) or uncertainty < 0:
                        raise ValueError("invalid WSL clock offset or uncertainty")
                    lower_bound = max(0.0, abs(offset_seconds) - uncertainty)
                    upper_bound = abs(offset_seconds) + uncertainty
            if lower_bound * 1000.0 > float(max_offset_ms):
                failures.append(
                    f"WSL host clock offset {offset_seconds * 1000.0:.3f}ms exceeds "
                    f"{float(max_offset_ms):.3f}ms"
                )
            elif upper_bound * 1000.0 > float(max_offset_ms):
                failures.append(
                    "WSL host clock measurement uncertainty overlaps the permitted offset; "
                    "no automatic clock adjustment was made"
                )
        else:
            if repair and (
                chrony.get("leap_status") != "Normal"
                or int(chrony.get("stratum") or 0) <= 0
            ):
                repair_evidence = _attempt_chrony_repair()
                chrony = _chrony_tracking()
                repaired = bool(
                    chrony.get("leap_status") == "Normal"
                    and int(chrony.get("stratum") or 0) > 0
                )
            authority = dict(chrony)
            if authority.get("leap_status") != "Normal":
                failures.append("chrony has no synchronized source")
            if int(authority.get("stratum") or 0) <= 0:
                failures.append("chrony stratum is not selectable")
            offset_seconds = float(authority.get("system_offset_seconds") or 0.0)
            if abs(offset_seconds) * 1000.0 > float(max_offset_ms):
                failures.append(
                    f"chrony system offset {offset_seconds * 1000.0:.3f}ms exceeds "
                    f"{float(max_offset_ms):.3f}ms"
                )
    except Exception as exc:
        failures.append(f"time authority check failed: {type(exc).__name__}: {exc}")

    completed = datetime.now(TAIPEI)
    return {
        "schema_version": 1,
        "status": "ok" if not failures else "failed",
        "ready": not failures,
        "repaired": repaired,
        "repair_evidence": repair_evidence,
        "simulation_schedule_authority": authority,
        "chrony_observation": chrony,
        "max_offset_ms": float(max_offset_ms),
        "max_repair_offset_seconds": float(max_repair_offset_seconds),
        "failures": failures,
        "started_at_taipei": started.isoformat(timespec="milliseconds"),
        "completed_at_taipei": completed.isoformat(timespec="milliseconds"),
    }


def _valid_wsl_rate_guard(value: object) -> bool:
    if (not isinstance(value, dict) or value.get("contract") != WSL_RATE_GUARD_CONTRACT
            or type(value.get("consecutive_good_samples")) is not int):
        return False
    count, status = value["consecutive_good_samples"], value.get("status")
    return ((status == "stable" and count == WSL_RATE_REQUIRED_GOOD_SAMPLES)
            or (status == "unstable" and count == 0)
            or (status == "recovering" and 0 < count < WSL_RATE_REQUIRED_GOOD_SAMPLES))


def _apply_wsl_rate_stability_guard(payload: dict[str, Any], previous: dict[str, Any] | None) -> None:
    """Keep a detected rate fault visible until five subsequent good checks.

    A single low offset or nominal tick is not evidence that a competing
    controller has stopped. The caller serializes this transition with the
    receipt write, so overlapping timers cannot lose a fault observation.
    """
    old = (previous or {}).get("wsl_rate_stability")
    if old is None and any("WSL kernel tick rate is abnormal" in str(item)
                           for item in (previous or {}).get("failures", ())):
        old = {"contract": WSL_RATE_GUARD_CONTRACT, "status": "unstable", "consecutive_good_samples": 0}
    if old is not None and not _valid_wsl_rate_guard(old):
        payload["failures"].append("previous WSL clock stability receipt is invalid")
        payload["ready"], payload["status"] = False, "failed"
        return
    old_active = bool(old and old["status"] in {"unstable", "recovering"})
    measured_wsl = (payload.get("simulation_schedule_authority") or {}).get("source") == "wsl_windows_host_clock"
    discipline = (payload.get("repair_evidence") or {}).get("kernel_time_discipline")
    rate_fault = (any("WSL kernel tick rate is abnormal" in str(item) for item in payload["failures"])
                  or measured_wsl and not isinstance(discipline, dict))
    if not measured_wsl and not old_active:
        return
    good = bool(payload.get("ready")) and measured_wsl
    if rate_fault or (old_active and not good):
        status, count = "unstable", 0
    elif old_active:
        count = min(WSL_RATE_REQUIRED_GOOD_SAMPLES, old["consecutive_good_samples"] + 1)
        status = "stable" if count >= WSL_RATE_REQUIRED_GOOD_SAMPLES else "recovering"
    else:
        status, count = "stable", WSL_RATE_REQUIRED_GOOD_SAMPLES
    payload["wsl_rate_stability"] = {"contract": WSL_RATE_GUARD_CONTRACT, "status": status,
        "consecutive_good_samples": count, "required_good_samples": WSL_RATE_REQUIRED_GOOD_SAMPLES,
        "max_estimated_rate_deviation_ppm": WSL_RATE_MAX_ESTIMATED_DEVIATION_PPM,
        "does_not_guarantee_future_stability": True}
    if status != "stable":
        payload["failures"].append("WSL clock rate remains unstable or is awaiting consecutive verified samples")
        payload["ready"], payload["status"] = False, "failed"


def main() -> int:
    args = parse_args()
    if args.max_offset_ms <= 0 or args.max_repair_offset_seconds <= 0:
        raise ValueError("clock thresholds must be positive")
    receipt = _repo_path(args.receipt)
    receipt.parent.mkdir(parents=True, exist_ok=True)
    lock_path = receipt.with_name(receipt.name + ".lock")
    with lock_path.open("a+") as lock:
        deadline = time.monotonic() + 5.0
        while True:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    raise RuntimeError("time sync receipt is owned by another active check")
                time.sleep(0.05)
        previous = None
        if receipt.exists():
            previous = json.loads(receipt.read_text(encoding="utf-8"))
            if not isinstance(previous, dict):
                raise ValueError("previous time sync receipt is not an object")
        old_guard = (previous or {}).get("wsl_rate_stability")
        prior_rate_unstable = (
            old_guard is not None and (not _valid_wsl_rate_guard(old_guard) or old_guard["status"] != "stable")
            or any("WSL kernel tick rate is abnormal" in str(item)
                   for item in (previous or {}).get("failures", ()))
        )
        # Do not step the shared clock during the recovery window merely
        # because this single tick sample happened to be near nominal.
        payload = evaluate_time_sync(
            repair=bool(args.repair) and not prior_rate_unstable,
            max_offset_ms=float(args.max_offset_ms),
            max_repair_offset_seconds=float(args.max_repair_offset_seconds),
            samples=int(args.samples),
        )
        _apply_wsl_rate_stability_guard(payload, previous)
        _atomic_json(receipt, payload)
        run_id = datetime.now(TAIPEI).strftime("%Y%m%dT%H%M%S%f")
        _atomic_json(receipt.parent / "runs" / f"{run_id}.json", payload)
        _prune_managed_runs(receipt.parent / "runs")
    print(json.dumps(payload, ensure_ascii=False, sort_keys=True), flush=True)
    return 0 if payload["ready"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
