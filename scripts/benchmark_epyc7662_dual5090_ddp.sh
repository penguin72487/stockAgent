#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

export CUDA_DEVICE_ORDER="${CUDA_DEVICE_ORDER:-PCI_BUS_ID}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1}"

# Two DDP ranks share the EPYC 7662. Keep each rank to half the logical threads
# and keep Inductor compile workers bounded to avoid long CPU oversubscription.
export STOCKAGENT_DDP_NPROC="${STOCKAGENT_DDP_NPROC:-2}"
export STOCKAGENT_DDP_RANK_CPU_THREADS="${STOCKAGENT_DDP_RANK_CPU_THREADS:-64}"
export STOCKAGENT_DDP_COMPILE_THREADS="${STOCKAGENT_DDP_COMPILE_THREADS:-16}"
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export MKL_NUM_THREADS="${MKL_NUM_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export OPENBLAS_NUM_THREADS="${OPENBLAS_NUM_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export NUMEXPR_NUM_THREADS="${NUMEXPR_NUM_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export POLARS_MAX_THREADS="${POLARS_MAX_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export RAYON_NUM_THREADS="${RAYON_NUM_THREADS:-$STOCKAGENT_DDP_RANK_CPU_THREADS}"
export TORCHINDUCTOR_COMPILE_THREADS="${TORCHINDUCTOR_COMPILE_THREADS:-$STOCKAGENT_DDP_COMPILE_THREADS}"

export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"
export PYTORCH_ALLOC_CONF="${PYTORCH_ALLOC_CONF:-$PYTORCH_CUDA_ALLOC_CONF}"
export TORCHINDUCTOR_CACHE_DIR="${TORCHINDUCTOR_CACHE_DIR:-$HOME/.cache/torchinductor}"
export TRITON_CACHE_DIR="${TRITON_CACHE_DIR:-$HOME/.cache/triton}"
export CUDA_CACHE_PATH="${CUDA_CACHE_PATH:-$HOME/.cache/nv_cuda}"

CONFIG_PATH="${STOCKAGENT_DDP_CONFIG:-configs/markets/tw_parallel.yaml}"
FOLD_INDEX="${STOCKAGENT_DDP_FOLD_INDEX:-23}"
GLOBAL_BATCH_SIZE="${STOCKAGENT_DDP_GLOBAL_BATCH_SIZE:-128}"
TIMED_BATCHES="${STOCKAGENT_DDP_BATCHES:-40}"
WARMUP_BATCHES="${STOCKAGENT_DDP_WARMUP:-2}"
BUCKET_CAP_MB="${STOCKAGENT_DDP_BUCKET_CAP_MB:-4}"

exec /venv/fintech/bin/python -m torch.distributed.run \
  --standalone \
  --nproc_per_node="$STOCKAGENT_DDP_NPROC" \
  scripts/benchmark_ddp_async_backprop.py \
  --config "$CONFIG_PATH" \
  --fold-index "$FOLD_INDEX" \
  --global-batch-size "$GLOBAL_BATCH_SIZE" \
  --batches "$TIMED_BATCHES" \
  --warmup "$WARMUP_BATCHES" \
  --rank-cpu-threads "$STOCKAGENT_DDP_RANK_CPU_THREADS" \
  --bucket-cap-mb "$BUCKET_CAP_MB" \
  --compile-model \
  --compile-mode default \
  --no-compile-loss \
  "$@"
